-- 阶段是剧情突破的结果；不能让高好感跳过剧情门槛。
local function current_tier()
    local rel = data.get_relation("reimu")
    local stage = data.get_stage("reimu")
    if rel < 0 then
        return "cold"
    end
    if rel < 10 then
        return "neutral"
    end

    -- 按关系突破事件给出的 stage，限制当前能看见的最高话题级别。
    local stage_rank = {
        friendly = 1, close = 2, love = 3, soulmate = 4,
    }
    local rank = stage_rank[stage] or 0
    if rank == 0 then return "neutral" end
    if rel < 30 or rank == 1 then return "friendly" end
    if rel < 60 or rank == 2 then return "close" end
    if rel < 80 or rank == 3 then return "love" end
    return "soulmate"
end

-- 先过滤时段，再去掉上一条；只有一个符合条件时允许重复。
local function choose(bank, key)
    local now = world.get_time()
    local last = data.get_flag("reimu", key, 0)
    local valid = {}
    local other = {}
    for i, entry in ipairs(bank) do
        if entry.time == nil or entry.time == now then
            valid[#valid + 1] = i
            if i ~= last then
                other[#other + 1] = i
            end
        end
    end
    if #valid == 0 then return nil end
    if #other == 0 then other = valid end
    local index = other[util.random_range(1, #other)]
    data.set_flag("reimu", key, index)
    return bank[index]
end

local function display(entry)
    if entry == nil then return end
    for _, line in ipairs(entry.lines) do
        if line[1] == "R" then
            ui.text("灵梦：" .. line[2], "pink")
        elseif line[1] == "N" then
            ui.text(line[2], "white")
        elseif line[1] == "H" then
            ui.show_character("reimu", line[2], "center")
        end
    end
end

return {
    on_event = "dialogue:reimu",
    hub = {
        char = "reimu",
        label = "聊聊",
        order = 10,
        daily_limit = 3,
    },
    execute = function()
        data.log_start("reimu", "闲聊")
        local tier = current_tier()
        local scripts = BANK[tier]
        ui.set_background("shrine", "fade")
        ui.show_character("reimu", "normal", "center")
        display(choose(scripts.hello, "last_daily_hello_" .. tier))

        local choice = ui.ask_choice({ "随便聊聊", "帮忙做事", "告辞" })
        if choice == 1 then
            display(choose(scripts.chat, "last_daily_chat_" .. tier))
            data.modify_relation("reimu", 1)
        elseif choice == 2 then
            display(choose(scripts.help, "last_daily_help_" .. tier))
            data.modify_relation("reimu", 3)
            data.modify_stat("player", "stamina", -5)
            ui.text("（好感 +3，体力 -5）", "gray")
        else
            display(choose(scripts.bye, "last_daily_bye_" .. tier))
        end

        ui.hide_character("reimu")
        data.log_commit()
    end,
}
